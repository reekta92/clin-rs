macro_rules! palette_aliases {
    ($action:ty, $($variant:ident => $id:literal),* $(,)?) => {
        impl $action {
            pub(crate) fn palette_action_id(self) -> Option<&'static str> {
                match self { $(Self::$variant => Some($id),)* _ => None }
            }
        }
    };
}

